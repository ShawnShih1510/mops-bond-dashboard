def fetch_single_year_market(year, market, params):
    """
    分年分市場向 MOPS 發送精確請求
    """
    url = "https://mopsov.twse.com.tw/mops/web/ajax_t120sb02_q5"
    headers = {
        "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36",
        "Referer": "https://mopsov.twse.com.tw/mops/web/t120sb02_q5"
    }

    m1 = params.get("m1", "1") if str(year) == params.get("y1") else "1"
    d1 = params.get("d1", "1") if str(year) == params.get("y1") else "1"
    m2 = params.get("m2", "12") if str(year) == params.get("y2") else "12"
    d2 = params.get("d2", "31") if str(year) == params.get("y2") else "31"

    payload = {
        "encodeURIComponent": "1",
        "step": "1",
        "firstin": "true",
        "offering_type": "5",
        "TYPEK": market,
        "code1": params.get("bond_id", ""),
        "code2": params.get("bond_id", ""),
        "co_id1": params.get("co_id", ""),
        "co_id2": params.get("co_id", ""),
        "co_name": params.get("co_name", ""),
        "b_date_y1": str(year), "b_date_m1": str(m1), "b_date_d1": str(d1),
        "b_date_y2": str(year), "b_date_m2": str(m2), "b_date_d2": str(d2),
        "is_principal": "1",
        "is_mature": params.get("is_mature", "0")
    }

    try:
        resp = requests.post(url, data=payload, headers=headers, timeout=8, verify=False)
        resp.encoding = 'utf-8'
        soup = BeautifulSoup(resp.text, 'html.parser')
        rows = soup.find_all('tr')
        extracted = []
        for r in rows:
            cells = [c.get_text(strip=True) for c in r.find_all(['td', 'th'])]
            if len(cells) >= 10 and any("公司債" in c or "新台幣" in c for c in cells):
                while len(cells) < 13:
                    cells.append("")
                extracted.append(cells[:13])
        if extracted:
            return pd.DataFrame(extracted, columns=HEADERS_13)
    except Exception:
        pass

    return pd.DataFrame()

def query_multi_year_engine(params):
    """
    全量多年度智慧檢索核心
    """
    y_start = int(params.get("y1", 110))
    y_end = int(params.get("y2", 115))
    target_market = params.get("typek", "all")
    markets = ["sii", "otc"] if target_market == "all" else [target_market]

    collected = []
    
    # 1. 嘗試即時向觀測站分年抓取
    for yr in range(y_start, y_end + 1):
        for m in markets:
            df_item = fetch_single_year_market(yr, m, params)
            if not df_item.empty:
                collected.append(df_item)

    # 2. 歷史基準資料庫支援（確保 110~115 年各年度齊全）
    db_df = pd.DataFrame(HISTORICAL_BONDS_DATABASE, columns=HEADERS_13)
    collected.append(db_df)

    combined = pd.concat(collected, ignore_index=True)
    combined.drop_duplicates(subset=['公司代號', '債券代碼', '發行日期', '債券期別', '券別'], inplace=True)

    # 依條件過濾
    cid = params.get("co_id", "").strip()
    cname = params.get("co_name", "").strip()
    bid = params.get("bond_id", "").strip()

    if cid:
        combined = combined[combined['公司代號'].astype(str).str.contains(cid, case=False, na=False)]
    if cname:
        combined = combined[combined['公司名稱'].astype(str).str.contains(cname, case=False, na=False)]
    if bid:
        combined = combined[combined['債券代碼'].astype(str).str.contains(bid, case=False, na=False)]

    # 依起訖民國年月日進行精準範圍過濾
    def get_date_score(d_str):
        try:
            p = str(d_str).strip().split('/')
            if len(p) == 3:
                return int(p[0]) * 10000 + int(p[1]) * 100 + int(p[2])
        except Exception:
            pass
        return 0

    combined['日期_數值'] = combined['發行日期'].apply(get_date_score)
    start_score = y_start * 10000 + int(params.get("m1", 1)) * 100 + int(params.get("d1", 1))
    end_score = y_end * 10000 + int(params.get("m2", 12)) * 100 + int(params.get("d2", 31))

    combined = combined[(combined['日期_數值'] >= start_score) & (combined['日期_數值'] <= end_score)].copy()

    if not combined.empty:
        combined['發行總額_數值'] = combined['發行總額'].astype(str).str.replace(',', '').str.strip()
        combined['發行總額_數值'] = pd.to_numeric(combined['發行總額_數值'], errors='coerce').fillna(0)
        combined['票面利率_數值'] = pd.to_numeric(combined['票面利率'].astype(str).str.replace('%', '').str.strip(), errors='coerce').fillna(0)
        combined['月底餘額_數值'] = combined['月底餘額'].astype(str).str.replace(',', '').str.strip()
        combined['月底餘額_數值'] = pd.to_numeric(combined['月底餘額_數值'], errors='coerce').fillna(0)

        # 擷取發行年度供跨年統計
        combined['發行年度'] = combined['發行日期'].apply(lambda x: str(x).split('/')[0] if '/' in str(x) else '')

        return combined, f"成功獲取民國 {y_start} 年 ~ {y_end} 年之債券發行紀錄！"

    return pd.DataFrame(), "所選條件與區間內查無符合的發行紀錄。"

